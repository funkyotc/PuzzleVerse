def build_tray_str(grid_matrix, seed_offset):
    # Count occurrences of each color
    counts = {}
    for r in grid_matrix:
        for cell in r:
            if cell is not None:
                counts[cell] = counts.get(cell, 0) + 1
                
    rand = random.Random(20240801 + seed_offset)
    tanks = []
    
    for color in sorted(counts.keys()):
        rem = counts[color]
        while rem > 0:
            ammo = min(rem, 20 if rem >= 20 else 15 if rem >= 15 else 10 if rem >= 10 else 5 if rem >= 5 else rem)
            tanks.append((color, ammo))
            rem -= ammo
            
    rand.shuffle(tanks)
    return ";".join(f"{c},{a}" for c, a in tanks)

def grid_to_str(grid_matrix):
    rows = []
    for r in grid_matrix:
        row_str = ",".join(str(cell) if cell is not None else "" for cell in r)
        rows.append(row_str)
    return "|".join(rows)

def generate_files():
    all_levels_meta = [] # (id, name, diff, cols, rows, grid_str, tray_str, chunk_name)
    
    idx = 1
    # Easy
    for name, art in EASY_ART:
        g = parse_art(art.split('\n'), 15, 15)
        grid_s = grid_to_str(g)
        tray_s = build_tray_str(g, idx)
        chunk = f"CHUNK_EASY_{idx}"
        level_id = f"cubeshooter_easy_{idx:03d}"
        all_levels_meta.append((level_id, name, "Easy", 15, 15, grid_s, tray_s, chunk))
        idx += 1
        
    idx = 1
    # Medium
    for name, art in MEDIUM_ART:
        g = parse_art(art.split('\n'), 20, 20)
        grid_s = grid_to_str(g)
        tray_s = build_tray_str(g, idx + 100)
        chunk = f"CHUNK_MEDIUM_{idx}"
        level_id = f"cubeshooter_medium_{idx:03d}"
        all_levels_meta.append((level_id, name, "Medium", 20, 20, grid_s, tray_s, chunk))
        idx += 1
        
    idx = 1
    # Hard
    for name, art in HARD_ART:
        g = parse_art(art.split('\n'), 30, 30)
        grid_s = grid_to_str(g)
        tray_s = build_tray_str(g, idx + 200)
        chunk = f"CHUNK_HARD_{idx}"
        level_id = f"cubeshooter_hard_{idx:03d}"
        all_levels_meta.append((level_id, name, "Hard", 30, 30, grid_s, tray_s, chunk))
        idx += 1

    # Generate CubeShooterPregenerated.kt
    sb = []
    sb.append("package com.funkyotc.puzzleverse.cubeshooter.data")
    sb.append("")
    sb.append("import com.funkyotc.puzzleverse.core.data.BrowseablePuzzle")
    sb.append("")
    sb.append("data class PregeneratedLevel(")
    sb.append("    override val id: String,")
    sb.append("    val name: String,")
    sb.append("    override val difficulty: String,")
    sb.append("    val cols: Int,")
    sb.append("    val rows: Int,")
    sb.append("    val grid: List<List<Int?>>,")
    sb.append("    val tray: List<Tank>")
    sb.append(") : BrowseablePuzzle {")
    sb.append("    override val label: String get() = name")
    sb.append("    override val subtitle: String get() = \"${cols}x${rows}\"")
    sb.append("}")
    sb.append("")
    sb.append("object CubeShooterPregenerated {")
    sb.append("")
    sb.append("    private fun parseLevel(")
    sb.append("        id: String, name: String, difficulty: String, cols: Int, rows: Int,")
    sb.append("        grid: String, tray: String")
    sb.append("    ): PregeneratedLevel {")
    sb.append("        val parsedGrid = grid.split('|').map { row ->")
    sb.append("            row.split(',').map { it.toIntOrNull() }")
    sb.append("        }")
    sb.append("        val parsedTray = tray.split(';').map { part ->")
    sb.append("            val (c, a) = part.split(',').map { it.toInt() }")
    sb.append("            Tank(c, a)")
    sb.append("        }")
    sb.append("        return PregeneratedLevel(id, name, difficulty, cols, rows, parsedGrid, parsedTray)")
    sb.append("    }")
    sb.append("")
    
    chunk_names = []
    for lid, name, diff, cols, rows, grid_s, tray_s, chunk in all_levels_meta:
        chunk_names.append(chunk)
        sb.append(f"    private val {chunk} by lazy {{")
        sb.append("        parseLevel(")
        sb.append(f'            "{lid}", "{name}", "{diff}", {cols}, {rows},')
        sb.append(f'            grid = "{grid_s}",')
        sb.append(f'            tray = "{tray_s}"')
        sb.append("        )")
        sb.append("    }")
        sb.append("")
        
    sb.append("    val ALL_LEVELS: List<PregeneratedLevel> by lazy {")
    sb.append(f"        listOf({', '.join(chunk_names)})")
    sb.append("    }")
    sb.append("")
    sb.append("    val LEVELS_BY_DIFFICULTY: Map<String, List<PregeneratedLevel>> by lazy { ALL_LEVELS.groupBy { it.difficulty } }")
    sb.append("}")

    target_kt = "app/src/main/java/com/funkyotc/puzzleverse/cubeshooter/data/CubeShooterPregenerated.kt"
    os.makedirs(os.path.dirname(target_kt), exist_ok=True)
    with open(target_kt, "w", encoding="utf-8") as f:
        f.write("\n".join(sb))
        
    print(f"Successfully generated {len(all_levels_meta)} levels into {target_kt}")

if __name__ == "__main__":
    generate_files()
