# Color Palette mapping for Cube Shooter
# 0: CYAN (C)
# 1: MAGENTA (M)
# 2: YELLOW (Y)
# 3: GREEN (G)
# 4: ORANGE (O)
# 5: PURPLE (P)
# 6: RED (R)
# 7: BLUE (B)
# 8: TEAL (T)
# 9: PINK (K)
# 10: INDIGO (I)
# 11: LIME (L)
# '.' or ' ': Empty / null

CHAR_TO_COLOR = {
    'C': 0, 'M': 1, 'Y': 2, 'G': 3, 'O': 4,
    'P': 5, 'R': 6, 'B': 7, 'T': 8, 'K': 9,
    'I': 10, 'L': 11
}

def parse_art(art_lines, target_cols, target_rows):
    lines = [line.rstrip('\r\n') for line in art_lines if line.strip() != '']
    rows = len(lines)
    cols = max(len(l) for l in lines) if lines else 0
    
    # Grid initialization
    grid = [[None for _ in range(target_cols)] for _ in range(target_rows)]
    
    row_offset = max(0, (target_rows - rows) // 2)
    col_offset = max(0, (target_cols - cols) // 2)
    
    for r in range(min(rows, target_rows)):
        line = lines[r]
        for c in range(min(len(line), target_cols)):
            char = line[c]
            if char in CHAR_TO_COLOR:
                grid[r + row_offset][c + col_offset] = CHAR_TO_COLOR[char]
                
    return grid

