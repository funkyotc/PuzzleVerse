/**
 * Pre-generated Hexa Stack levels, built offline by [HexaStackGenerator] (see HexaStackGenTest)
 * and verified winnable via the generator's greedy auto-player replay.
 *
 * Win condition: reach [HexaStackLevel.scoreTarget] (10 points per popped tile).
 */
data class PregeneratedHexaStack(
    override val id: String,
    override val difficulty: String,
    val radius: Int,
    val scoreTarget: Int,
    val initialStacks: Map<AxialCoord, List<Int>> = emptyMap(),
    val spawnDeck: List<List<Int>>
) : BrowseablePuzzle {
    override val label: String get() = "Puzzle ${id.takeLast(3)}"
    override val subtitle: String get() = "Target $scoreTarget"

    fun toLevel(): HexaStackLevel = HexaStackLevel(id, difficulty, radius, scoreTarget, initialStacks, spawnDeck)
}

